#!/usr/bin/env python3
"""Split the RIXE specification into one file per top-level section, or join it back.

Usage (from the repository root):
  python Tools/split_spec.py split [--spec CAHIER_DES_CHARGES_RIXE.md] [--out spec]
  python Tools/split_spec.py join  [--out spec] [--spec CAHIER_DES_CHARGES_RIXE.md]
  python Tools/split_spec.py check [--spec CAHIER_DES_CHARGES_RIXE.md] [--out spec]

`split` is lossless: `check` rebuilds the original text from the parts and compares it byte for byte.
Parts are listed in spec/ORDER.txt (one file name per line); `join` concatenates them in that order.
Headings inside fenced code blocks are ignored.
"""
from __future__ import annotations

import argparse
import re
import sys
import unicodedata
from pathlib import Path

HEADING = re.compile(r"^## (.+?)\s*$")
NUMBER = re.compile(r"^(\d+)\.\s")


def slugify(text: str, limit: int = 48) -> str:
    ascii_text = unicodedata.normalize("NFKD", text).encode("ascii", "ignore").decode("ascii")
    slug = re.sub(r"[^a-z0-9]+", "-", ascii_text.lower()).strip("-")
    return slug[:limit].rstrip("-") or "section"


def split_text(text: str) -> list[tuple[str, str, str]]:
    """Return (file_name, title, content) triples; content parts concatenate back to `text`."""
    lines = text.splitlines(keepends=True)
    parts: list[tuple[str, list[str]]] = [("Preamble", [])]
    in_fence = False
    for line in lines:
        if line.lstrip().startswith("```"):
            in_fence = not in_fence
        match = None if in_fence else HEADING.match(line.rstrip("\n"))
        if match:
            parts.append((match.group(1), [line]))
        else:
            parts[-1][1].append(line)

    result: list[tuple[str, str, str]] = []
    used: set[str] = set()
    unnumbered = 0
    for index, (title, body) in enumerate(parts):
        if index == 0:
            name = "00-preamble.md"
        else:
            number = NUMBER.match(title)
            if number:
                prefix = f"{int(number.group(1)):03d}"
                title_for_slug = title[number.end():]
            else:
                title_for_slug = title
                unnumbered += 1
                prefix = f"000-{unnumbered}"
            name = f"{prefix}-{slugify(title_for_slug)}.md"
        while name in used:  # duplicate section numbers stay distinct
            name = name.replace(".md", "-b.md")
        used.add(name)
        result.append((name, title, "".join(body)))
    return result


def write_index(out: Path, parts: list[tuple[str, str, str]]) -> None:
    rows = ["# Specification index", "", "Generated by `Tools/split_spec.py`. Edit the section files, not this index.", "",
            "| File | Title | Lines | KB |", "|---|---|---:|---:|"]
    for name, title, content in parts:
        rows.append(f"| [{name}]({name}) | {title} | {content.count(chr(10))} | {len(content.encode('utf-8')) / 1024:.1f} |")
    (out / "INDEX.md").write_text("\n".join(rows) + "\n", encoding="utf-8", newline="\n")
    (out / "ORDER.txt").write_text("".join(f"{name}\n" for name, _, _ in parts), encoding="utf-8", newline="\n")


def join_parts(out: Path) -> str:
    order = [line.strip() for line in (out / "ORDER.txt").read_text(encoding="utf-8").splitlines() if line.strip()]
    return "".join((out / name).read_text(encoding="utf-8") for name in order)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("command", choices=["split", "join", "check"])
    parser.add_argument("--spec", default="CAHIER_DES_CHARGES_RIXE.md")
    parser.add_argument("--out", default="spec")
    args = parser.parse_args()
    spec, out = Path(args.spec), Path(args.out)

    if args.command == "split":
        text = spec.read_text(encoding="utf-8")
        parts = split_text(text)
        out.mkdir(parents=True, exist_ok=True)
        for name, _, content in parts:
            (out / name).write_text(content, encoding="utf-8", newline="\n")
        write_index(out, parts)
        if join_parts(out) != text:
            print("FAILED: split is not lossless", file=sys.stderr)
            return 1
        print(f"OK: {len(parts)} files written to {out}/ (lossless)")
        return 0
    if args.command == "join":
        spec.write_text(join_parts(out), encoding="utf-8", newline="\n")
        print(f"OK: {spec} rebuilt from {out}/")
        return 0
    same = join_parts(out) == spec.read_text(encoding="utf-8")
    print("OK: parts match the single file" if same else "FAILED: parts differ from the single file")
    return 0 if same else 1


if __name__ == "__main__":
    raise SystemExit(main())
